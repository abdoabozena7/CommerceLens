import { expect, test } from '@playwright/test'
import type { CommerceAnalytics, Order, Overview, Product } from '../../frontend/src/services/types.ts'
import { getApi } from './api.ts'

test('catalog, details, checkout and cross-tab dashboard refresh use persisted API data', async ({ page, request, context }) => {
  const before = await getApi<Overview>(request, '/analytics/overview')
  const products = await getApi<Product[]>(request, '/products')
  const arc = products.find(product => product.slug === 'arc-headphones')!
  const dashboard = await context.newPage()
  await dashboard.goto('/')
  await expect(dashboard.getByTestId('orders-kpi')).toHaveText(String(before.totalOrders))
  await page.goto('/store')
  await expect(page.getByTestId('product-card')).toHaveCount(8)
  await page.getByLabel('Search products').fill('Arc')
  await expect(page.getByTestId('product-card')).toHaveCount(1)
  await expect(page.getByTestId('product-price')).toHaveText('$129.00')
  await page.getByRole('button', { name: 'View details' }).click()
  await expect(page.getByRole('heading', { name: arc.name })).toBeVisible()
  await page.getByRole('button', { name: 'Add to cart' }).click()
  await expect(page.getByRole('dialog', { name: 'Shopping cart' })).toBeVisible()
  await page.getByRole('button', { name: `Add one ${arc.name}` }).click()
  const placed = page.waitForResponse(response => response.url().endsWith('/api/orders') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Place demo order' }).click()
  const orderResponse = await placed
  expect(orderResponse.status()).toBe(201)
  const order: Order = await orderResponse.json()
  expect(order.total).toBe(arc.price * 2)
  expect(order.sourceType).toBe('LocalDemoCheckout')
  await expect(page.getByTestId('order-confirmation')).toContainText(`Order #${order.id} is saved`)
  await expect(dashboard.getByTestId('orders-kpi')).toHaveText(String(before.totalOrders + 1))
  await expect(dashboard.getByTestId('revenue-kpi')).toHaveText(
    new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(before.revenue + order.total))
  await dashboard.reload()
  await expect(dashboard.getByTestId('orders-kpi')).toHaveText(String(before.totalOrders + 1))
  const updated = await getApi<Product>(request, `/products/${arc.id}`)
  expect(updated.stock).toBe(arc.stock - 2)
  const sales = await getApi<CommerceAnalytics>(request, '/analytics/commerce')
  expect(sales.revenue).toBe(before.revenue + order.total)
  expect(sales.averageOrderValue).toBe(sales.revenue / sales.totalOrders)
  expect(sales.topProducts.find(product => product.name === arc.name)?.units).toBeGreaterThanOrEqual(2)
  expect(sales.byCategory.find(category => category.name === arc.category)?.revenue).toBeGreaterThanOrEqual(order.total)
  expect(sales.dailySales.reduce((sum, day) => sum + day.revenue, 0)).toBe(sales.revenue)
  const unchangedHistory = await getApi<Overview>(request, '/analytics/overview')
  expect(unchangedHistory.totalObservations).toBe(10_000)
  expect(unchangedHistory.totalHistoricalClicks).toBe(6_500)
  await page.getByRole('button', { name: 'Close cart' }).click()
  await page.getByRole('link', { name: 'Back to the collection' }).click()
  await page.getByRole('button', { name: 'Electronics', exact: true }).click()
  await expect(page.getByTestId('product-card')).toHaveCount(2)
  await page.getByLabel('Sort products').selectOption('priceDesc')
  await expect(page.getByTestId('product-card').first()).toContainText(arc.name)
  await dashboard.close()
})

test('public ad clicks are recorded separately from historical labels and orders', async ({ page, request }) => {
  const before = await getApi<Overview>(request, '/analytics/overview')
  await page.goto('/store')
  await expect(page.getByTestId('product-card')).toHaveCount(8)
  const featured = page.getByTestId('product-card').filter({ has: page.getByTestId('ad-text') }).first()
  const title = await featured.getByTestId('product-name').innerText()
  await featured.getByTestId('ad-text').click()
  await expect(page).toHaveURL(/\/store\/products\/\d+$/)
  await expect(page.getByRole('heading', { name: title, level: 1, exact: true })).toBeVisible()
  const after = await getApi<Overview>(request, '/analytics/overview')
  expect(after.liveAdClicks).toBe(before.liveAdClicks + 1)
  expect(after.liveAdImpressions).toBeGreaterThan(before.liveAdImpressions)
  expect(after.liveCtr).toBe(after.liveAdClicks / after.liveAdImpressions)
  expect(after.totalHistoricalClicks).toBe(6_500)
  expect(after.totalOrders).toBe(before.totalOrders)
})

test('ad impressions require 50 percent visibility and do not repeat on rerenders or filtering', async ({ page, request }) => {
  await page.setViewportSize({ width: 1440, height: 450 })
  const before = await getApi<Overview>(request, '/analytics/overview')
  const impressions: string[] = []
  page.on('request', message => {
    if (message.url().endsWith('/api/events') && message.method() === 'POST') {
      const event = message.postDataJSON() as { eventType: string; eventKey: string }
      if (event.eventType === 'AdImpression') impressions.push(event.eventKey)
    }
  })
  await page.goto('/store')
  await expect(page.getByTestId('product-card')).toHaveCount(8)
  const ads = page.getByTestId('ad-text')
  await expect(ads).toHaveCount(3)
  await expect(ads.first()).not.toBeInViewport()
  await ads.first().evaluate(element => {
    const box = element.getBoundingClientRect()
    const visiblePixels = Math.floor(box.height * 0.5) - 1
    window.scrollBy(0, box.top - window.innerHeight + visiblePixels)
  })
  const fraction = await ads.first().evaluate(element => {
    const box = element.getBoundingClientRect()
    return Math.max(0, Math.min(box.bottom, window.innerHeight) - Math.max(box.top, 0)) / box.height
  })
  expect(fraction).toBeGreaterThan(0.4)
  expect(fraction).toBeLessThan(0.5)
  // A bounded observation window asserts the absence of an asynchronous event below the threshold.
  await page.waitForTimeout(350)
  expect(impressions).toHaveLength(0)
  for (const ad of await ads.all()) await ad.scrollIntoViewIfNeeded()
  await expect.poll(async () => (await getApi<Overview>(request, '/analytics/overview')).liveAdImpressions)
    .toBe(before.liveAdImpressions + 3)
  await page.getByRole('button', { name: 'Electronics', exact: true }).click()
  await expect(page.getByTestId('product-card')).toHaveCount(2)
  await page.getByTestId('ad-text').scrollIntoViewIfNeeded()
  await page.getByRole('button', { name: 'All products', exact: true }).click()
  await expect(page.getByTestId('product-card')).toHaveCount(8)
  for (const ad of await page.getByTestId('ad-text').all()) await ad.scrollIntoViewIfNeeded()
  await page.getByRole('button', { name: /^Cart / }).click()
  await page.getByRole('button', { name: 'Close cart' }).click()
  await page.waitForTimeout(350)
  expect(impressions).toHaveLength(3)
  expect(new Set(impressions).size).toBe(3)
  expect((await getApi<Overview>(request, '/analytics/overview')).liveAdImpressions).toBe(before.liveAdImpressions + 3)
  await page.reload()
  await expect(page.getByTestId('product-card')).toHaveCount(8)
  for (const ad of await page.getByTestId('ad-text').all()) await ad.scrollIntoViewIfNeeded()
  await expect.poll(async () => (await getApi<Overview>(request, '/analytics/overview')).liveAdImpressions)
    .toBe(before.liveAdImpressions + 6)
})

test('direct product detail visits create one view, not one event per cart rerender', async ({ page, request }) => {
  const product = (await getApi<Product[]>(request, '/products'))[0]
  const before = await getApi<Overview>(request, '/analytics/overview')
  await page.goto(`/store/products/${product.id}`)
  await expect(page.getByRole('heading', { name: product.name })).toBeVisible()
  await expect.poll(async () => (await getApi<Overview>(request, '/analytics/overview')).productViews)
    .toBe(before.productViews + 1)
  await page.getByRole('button', { name: 'Add to cart' }).click()
  await page.getByRole('button', { name: `Add one ${product.name}` }).click()
  await page.getByRole('button', { name: 'Close cart' }).click()
  expect((await getApi<Overview>(request, '/analytics/overview')).productViews).toBe(before.productViews + 1)
  await page.reload()
  await expect.poll(async () => (await getApi<Overview>(request, '/analytics/overview')).productViews)
    .toBe(before.productViews + 2)
})
