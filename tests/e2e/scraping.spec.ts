import { expect, test } from '@playwright/test'
import { extractRenderedProducts, localStorefrontUrl } from '../../scraper/src/adapter.ts'
import type { Overview, Product, ScrapeDetail, ScrapeSummary } from '../../frontend/src/services/types.ts'
import { getApi } from './api.ts'

test('the adapter reads visible rendered text rather than API or database values', async ({ page, request }) => {
  await page.goto('/store?collection=1')
  await expect(page.getByTestId('product-card')).toHaveCount(8)
  const first = page.getByTestId('product-card').first()
  const id = Number(await first.getAttribute('data-product-id'))
  await first.getByTestId('product-name').evaluate(element => { element.textContent = 'Rendered-only test title' })
  await first.getByTestId('product-price').evaluate(element => { element.textContent = '$147.25' })
  await first.getByTestId('product-category').evaluate(element => { element.textContent = 'Rendered category' })
  await first.getByTestId('product-availability').evaluate(element => { element.textContent = 'Sold out' })
  const extracted = await extractRenderedProducts(page)
  const record = extracted.find(record => record.storefrontProductId === id)
  expect(record?.name).toBe('Rendered-only test title')
  expect(record?.priceCents).toBe(14725)
  expect(record?.category).toBe('Rendered category')
  expect(record?.availability).toBe('Sold out')
  expect(record?.sourceUrl).toContain('/store')
  const original = await getApi<Product>(request, `/products/${id}`)
  expect(original.name).not.toBe(record?.name)
  expect(original.category).not.toBe(record?.category)
  expect(original.stock).toBeGreaterThan(0)
  await page.getByTestId('product-card').last().evaluate(element => element.remove())
  expect(await extractRenderedProducts(page)).toHaveLength(7)
  expect(() => localStorefrontUrl('https://example.com/store')).toThrow()
})

test('triggered scraping persists rendered products without creating customer events', async ({ page, request, baseURL }) => {
  const before = await getApi<Overview>(request, '/analytics/overview')
  await page.goto('/monitoring')
  await expect(page.getByRole('heading', { name: 'Product monitoring', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Collect product data' }).click()
  await expect(page.getByRole('heading', { name: /Collection #/ })).toBeVisible({ timeout: 60_000 })
  await expect(page.getByText('Arc Wireless Headphones', { exact: true })).toBeVisible()
  const runs = await getApi<ScrapeSummary[]>(request, '/scrapes')
  expect(runs[0].status).toBe('Completed')
  expect(runs[0].recordCount).toBe(8)
  const detail = await getApi<ScrapeDetail>(request, `/scrapes/${runs[0].id}`)
  expect(detail.matchedCount).toBe(8)
  expect(detail.missingCount).toBe(0)
  expect(detail.priceMismatchCount).toBe(0)
  expect(detail.comparisons.filter((row: { adText: string | null }) => row.adText)).toHaveLength(3)
  for (const row of detail.comparisons) {
    expect(row.status).toBe('Matched')
    expect(row.priceDifference).toBe(0)
    expect(row.catalogAvailability).toBe(row.collectedAvailability)
    expect(row.sourceUrl).toBe(new URL('/store?collection=1', baseURL).href)
    if (row.extractedAt === null) throw new Error('A collected product is missing its extraction timestamp.')
    expect(row.extractedAt).toMatch(/Z$/)
    expect(Number.isNaN(Date.parse(row.extractedAt))).toBe(false)
    expect(Date.parse(row.extractedAt)).toBeGreaterThanOrEqual(Date.parse(detail.startedAt))
    expect(Date.parse(row.extractedAt)).toBeLessThanOrEqual(Date.parse(detail.completedAt!))
  }
  const after = await getApi<Overview>(request, '/analytics/overview')
  expect(after.totalEvents).toBe(before.totalEvents)
  expect(after.liveAdImpressions).toBe(before.liveAdImpressions)
  expect(after.totalScrapedRecords).toBe(before.totalScrapedRecords + 8)
  expect(after.totalObservations).toBe(10_000)
  expect(after.totalHistoricalClicks).toBe(6_500)
  await expect(page.getByTestId('collected-products-kpi')).toHaveText('8')
  await expect(page.getByTestId('price-differences-kpi')).toHaveText('0')
  await expect(page.getByTestId('missing-products-kpi')).toHaveText('0')
  await expect(page.getByRole('heading', { name: 'Collection history', exact: true })).toBeVisible()
  await page.getByLabel('Comparison filter').selectOption('price')
  await expect(page.getByRole('heading', { name: 'No matching products' })).toBeVisible()
  await page.getByLabel('Comparison filter').selectOption('Matched')
  await expect(page.getByRole('table').filter({ has: page.getByRole('columnheader', { name: 'Price delta', exact: true }) }).locator('tbody tr')).toHaveCount(8)
  await page.reload()
  await expect(page.getByRole('heading', { name: /Collection #/ })).toBeVisible()
  await expect(page.getByText('Arc Wireless Headphones', { exact: true })).toBeVisible()
  await page.goto('/scraper')
  await expect(page).toHaveURL(/\/monitoring$/)
  await expect(page.getByRole('heading', { name: /Collection #/ })).toBeVisible()
})

test('product monitoring history and comparison controls remain usable on mobile', async ({ page, request }, info) => {
  const collected = await request.post('/api/scrapes')
  expect(collected.ok(), await collected.text()).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/monitoring')
  await expect(page.getByRole('heading', { name: 'Product monitoring', exact: true })).toBeVisible()
  await expect(page.getByTestId('collected-products-kpi')).toHaveText('8')
  await expect(page.getByRole('heading', { name: 'Collection history', exact: true })).toBeVisible()
  await page.getByLabel('Comparison filter').selectOption('Missing')
  await expect(page.getByRole('heading', { name: 'No matching products' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: info.outputPath('product-monitoring-mobile.png'), fullPage: true })
})
